// Builds database/seed.sql from data/seed-menu.json.
// Usage: node database/generate-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(fs.readFileSync(path.join(here, '../data/seed-menu.json'), 'utf8'));

const q = v => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const j = v => `${q(JSON.stringify(v))}::jsonb`;
const arr = a => `array[${a.map(q).join(', ')}]::text[]`;
const brand = `(select id from public.brands where slug = 'bowl-lab')`;
const ingr = slug => `(select id from public.ingredients where brand_id = ${brand} and slug = ${q(slug)})`;
const prod = slug => `(select id from public.products where brand_id = ${brand} and slug = ${q(slug)})`;
const grp = (p, g) => `(select id from public.option_groups where product_id = ${prod(p)} and slug = ${q(g)})`;

const out = [];
out.push('-- Generated by database/generate-seed.mjs from data/seed-menu.json. Do not edit by hand.');
out.push('-- Nutrition values are development estimates.');
out.push('begin;');

out.push(`
insert into public.nutrients (code, name, unit, daily_value, display_order) values
${seed.nutrients.map((n, i) => `  (${q(n.code)}, ${j({en: n.name})}, ${q(n.unit)}, ${n.dailyValue ?? 'null'}, ${i + 1})`).join(',\n')}
on conflict (code) do nothing;`);

const allergens = [
  ['milk', 'Milk', 'Leche', ['US9', 'EU14', 'CA']], ['egg', 'Egg', 'Huevo', ['US9', 'EU14', 'CA']],
  ['fish', 'Fish', 'Pescado', ['US9', 'EU14', 'CA']], ['shellfish', 'Crustacean shellfish', 'Crustáceos', ['US9', 'EU14', 'CA']],
  ['tree_nuts', 'Tree nuts', 'Frutos de cáscara', ['US9', 'EU14', 'CA']], ['peanuts', 'Peanuts', 'Cacahuates', ['US9', 'EU14', 'CA']],
  ['wheat', 'Wheat', 'Trigo', ['US9', 'CA']], ['gluten', 'Cereals containing gluten', 'Cereales con gluten', ['EU14', 'CA']],
  ['soy', 'Soy', 'Soya', ['US9', 'EU14', 'CA']], ['sesame', 'Sesame', 'Ajonjolí', ['US9', 'EU14', 'CA']],
  ['celery', 'Celery', 'Apio', ['EU14']], ['mustard', 'Mustard', 'Mostaza', ['EU14', 'CA']],
  ['sulphites', 'Sulphites', 'Sulfitos', ['EU14', 'CA']], ['lupin', 'Lupin', 'Altramuces', ['EU14']],
  ['molluscs', 'Molluscs', 'Moluscos', ['EU14', 'CA']],
];
out.push(`
insert into public.allergens (code, name, regimes) values
${allergens.map(([c, en, es, r]) => `  (${q(c)}, ${j({en, es})}, ${arr(r)})`).join(',\n')}
on conflict (code) do nothing;`);

const tags = [['vegan', 'Vegan', 'Vegano'], ['vegetarian', 'Vegetarian', 'Vegetariano'], ['gluten_free', 'Gluten-free', 'Sin gluten'],
  ['dairy_free', 'Dairy-free', 'Sin lácteos'], ['pescatarian', 'Pescatarian', 'Pescetariano'], ['halal', 'Halal', 'Halal'], ['kosher', 'Kosher', 'Kosher']];
out.push(`
insert into public.diet_tags (code, name) values
${tags.map(([c, en, es]) => `  (${q(c)}, ${j({en, es})})`).join(',\n')}
on conflict (code) do nothing;`);

const L = seed.location;
out.push(`
insert into public.organizations (name, slug) values ('Bowl Lab', 'bowl-lab');
insert into public.brands (org_id, name, slug, default_locale, locales)
  select id, ${q(seed.brand.name)}, 'bowl-lab', ${q(seed.brand.defaultLocale)}, ${arr(seed.brand.locales)} from public.organizations where slug = 'bowl-lab';
insert into public.locations (org_id, brand_id, name, timezone, currency, tax_mode, tax_rate_bps, allergen_regime, order_prefix)
  select b.org_id, b.id, ${q(L.name)}, ${q(L.timezone)}, ${q(L.currency)}, ${q(L.taxMode)}, ${L.taxRateBps}, ${q(L.allergenRegime)}, ${q(L.orderPrefix)}
  from public.brands b where b.slug = 'bowl-lab';`);

for (const i of seed.ingredients) {
  out.push(`
insert into public.ingredients (brand_id, slug, name, color, serving_grams, badges, nutrition_source)
  values (${brand}, ${q(i.id)}, ${j(i.name)}, ${q(i.color)}, ${i.servingGrams}, ${arr(i.badges)}, ${q(i.nutritionSource)});
insert into public.ingredient_nutrients (ingredient_id, nutrient_code, amount) values
${Object.entries(i.nutritionPerRegular).map(([k, v]) => `  (${ingr(i.id)}, ${q(k)}, ${v})`).join(',\n')};`);
  if (i.allergens.length) out.push(`insert into public.ingredient_allergens (ingredient_id, allergen_code) values ${i.allergens.map(a => `(${ingr(i.id)}, ${q(a)})`).join(', ')};`);
  if (i.dietTags.length) out.push(`insert into public.ingredient_diet_tags (ingredient_id, tag_code) values ${i.dietTags.map(t => `(${ingr(i.id)}, ${q(t)})`).join(', ')};`);
}

seed.products.forEach((p, pi) => {
  out.push(`
insert into public.products (brand_id, slug, kind, name, price_minor, sort_order)
  values (${brand}, ${q(p.id)}, ${q(p.kind)}, ${j(p.name)}, ${p.kind === 'simple' ? p.priceCents : 'null'}, ${pi});`);
  if (p.kind === 'simple') {
    out.push(`insert into public.product_nutrients (product_id, nutrient_code, amount) values
${Object.entries(p.nutrition).map(([k, v]) => `  (${prod(p.id)}, ${q(k)}, ${v})`).join(',\n')};`);
    return;
  }
  p.groups.forEach((g, gi) => {
    out.push(`insert into public.option_groups (product_id, slug, name, position, min_select, max_select, included_count, extra_price_minor, sets_base_price, half_and_half, allow_on_side)
  values (${prod(p.id)}, ${q(g.id)}, ${j(g.name)}, ${gi + 1}, ${g.min}, ${g.max}, ${g.includedCount}, ${g.extraPriceCents}, ${!!g.setsBasePrice}, ${!!g.halfAndHalf}, ${!!g.allowOnSide});`);
    out.push(`insert into public.option_group_items (group_id, ingredient_id, position, allowed_portions, price_minor, base_price_minor, portion_deltas_minor, premium) values
${g.items.map((it, ii) => `  (${grp(p.id, g.id)}, ${ingr(it.ingredientId)}, ${ii + 1}, ${arr(it.allowedPortions)}, ${it.priceCents}, ${it.basePriceCents ?? 'null'}, ${j(it.portionPriceDeltasCents ?? {})}, ${it.premium})`).join(',\n')};`);
  });
});

seed.signatures.forEach((s, si) => {
  out.push(`insert into public.signature_items (product_id, slug, name, badges, lines, position)
  values (${prod(s.productId)}, ${q(s.id)}, ${j(s.name)}, ${arr(s.badges)}, ${j(s.lines)}, ${si});`);
});

out.push(`
insert into public.availability (location_id, ingredient_id)
  select l.id, i.id from public.locations l join public.ingredients i on i.brand_id = l.brand_id;

-- Version 1 of the published menu: the seed itself (the publish-menu function compiles later versions).
insert into public.menu_versions (brand_id, version, payload, payload_sha256, notes)
  select id, 1, ${j(seed)}, encode(sha256(convert_to(${j(seed)}::text, 'UTF8')), 'hex'), 'Seed menu' from public.brands where slug = 'bowl-lab';
insert into public.location_menus (location_id, menu_version_id)
  select l.id, mv.id from public.locations l join public.menu_versions mv on mv.brand_id = l.brand_id and mv.version = 1;

commit;`);

fs.writeFileSync(path.join(here, 'seed.sql'), out.join('\n') + '\n');
console.log('wrote database/seed.sql');
